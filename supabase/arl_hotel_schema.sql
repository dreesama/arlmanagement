-- ARL Hotel Management: isolated Supabase PostgreSQL schema.
-- Run in a NEW project. Never run this against the existing Eflow database.
create schema if not exists private;
create table if not exists private.admin_emails (
  email text primary key check (email = lower(email)),
  created_at timestamptz not null default now()
);
revoke all on schema private from public, anon;
revoke all on all tables in schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create or replace function private.is_arl_admin()
returns boolean language sql stable security definer set search_path = ''
as $$ select (select auth.uid()) is not null and exists (
  select 1 from private.admin_emails
  where email = lower((select auth.jwt()->>'email'))
) $$;
revoke all on function private.is_arl_admin() from public, anon;
grant execute on function private.is_arl_admin() to authenticated;

create or replace function public.is_authorized_admin()
returns boolean language sql stable security invoker set search_path = ''
as $$ select private.is_arl_admin() $$;
revoke all on function public.is_authorized_admin() from public, anon;
grant execute on function public.is_authorized_admin() to authenticated;

create table if not exists public.rooms (
 id bigint generated by default as identity primary key,
 number text unique not null,
 floor integer not null,
 type text not null,
 "bedType" text not null,
 capacity integer not null check (capacity > 0),
 "ratePerNight" numeric(12,2) not null check ("ratePerNight" >= 0),
 status text not null default 'Available' check (status in ('Available','Occupied','Reserved','Maintenance')),
 amenities text[] not null default '{}',
 description text default '',
 image text default ''
);
create table if not exists public.guests (
 id bigint generated by default as identity primary key,
 "fullName" text not null,
 email text not null,
 phone text not null,
 "idType" text not null,
 "idNumber" text not null,
 address text not null,
 nationality text not null default 'Filipino',
 "isVip" boolean not null default false,
 notes text default '',
 "createdAt" text not null
);
create table if not exists public.reservations (
 id bigint generated by default as identity primary key,
 "reservationCode" text unique not null,
 "guestId" bigint not null references public.guests(id),
 "roomId" bigint not null references public.rooms(id),
 "checkInDate" text not null,
 "checkOutDate" text not null,
 nights integer not null check (nights > 0),
 adults integer not null check (adults >= 0),
 children integer not null default 0 check (children >= 0),
 status text not null default 'Confirmed' check (status in ('Pending','Confirmed','Checked-In','Checked-Out','Cancelled')),
 "totalAmount" numeric(12,2) not null default 0,
 "specialRequests" text default '',
 "actualCheckIn" text,
 "actualCheckOut" text,
 "createdAt" text not null
);
create table if not exists public.billings (
 id bigint generated by default as identity primary key,
 "invoiceNumber" text unique not null,
 "reservationId" bigint not null references public.reservations(id),
 "roomCharges" numeric(12,2) not null default 0,
 "extraCharges" numeric(12,2) not null default 0,
 subtotal numeric(12,2) not null default 0,
 "taxAmount" numeric(12,2) not null default 0,
 "serviceCharge" numeric(12,2) not null default 0,
 "discountAmount" numeric(12,2) not null default 0,
 "discountType" text not null default 'percentage',
 "discountValue" numeric(12,2) not null default 0,
 "grandTotal" numeric(12,2) not null default 0,
 "paidAmount" numeric(12,2) not null default 0,
 "balanceAmount" numeric(12,2) not null default 0,
 status text not null default 'Unpaid',
 "createdAt" text not null
);
create table if not exists public.billing_items (
 id bigint generated by default as identity primary key,
 "billingId" bigint not null references public.billings(id) on delete cascade,
 description text not null,
 quantity numeric(12,2) not null,
 "unitPrice" numeric(12,2) not null,
 amount numeric(12,2) not null
);
create table if not exists public.payments (
 id bigint generated by default as identity primary key,
 "billingId" bigint not null references public.billings(id),
 amount numeric(12,2) not null check (amount > 0),
 method text not null,
 "referenceNo" text default '',
 "paidAt" text not null,
 notes text default ''
);

-- A signed-in email is not enough; it must also appear in the private
-- allowlist which can only be managed using Supabase's SQL editor/management API.
do $pol$
declare t text;
begin
 foreach t in array array['rooms','guests','reservations','billings','billing_items','payments'] loop
  execute format('alter table public.%I enable row level security', t);
  execute format('drop policy if exists arl_admin_all on public.%I', t);
  execute format('create policy arl_admin_all on public.%I for all to authenticated using ((select private.is_arl_admin())) with check ((select private.is_arl_admin()))', t);
  execute format('revoke all on public.%I from anon', t);
  execute format('grant select, insert, update, delete on public.%I to authenticated', t);
 end loop;
end $pol$;
grant usage, select on all sequences in schema public to authenticated;

-- Atomic reservation + billing creation; locks the room to avoid double-booking.
create or replace function public.create_hotel_reservation(
 p_guest_id bigint, p_room_id bigint, p_checkin text, p_checkout text,
 p_nights integer, p_adults integer, p_children integer, p_special text default ''
) returns bigint language plpgsql security invoker set search_path = ''
as $$
declare r public.rooms%rowtype; rid bigint; bid bigint; total numeric(12,2); invoice text;
begin
 if not private.is_arl_admin() then raise exception 'Not authorized'; end if;
 if p_nights < 1 or p_adults < 0 or p_children < 0 or p_checkout <= p_checkin then raise exception 'Invalid reservation dates or guests'; end if;
 select * into r from public.rooms where id = p_room_id for update;
 if not found or r.status <> 'Available' then raise exception 'Room is not available'; end if;
 total := r."ratePerNight" * p_nights;
 insert into public.reservations (
  "reservationCode","guestId","roomId","checkInDate","checkOutDate",
  nights,adults,children,status,"totalAmount","specialRequests","createdAt")
 values (
  'ARL-'||extract(year from now())::text||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10)),
  p_guest_id,p_room_id,p_checkin,p_checkout,p_nights,p_adults,p_children,
  'Confirmed',total,coalesce(p_special,''),to_char(now() at time zone 'UTC','YYYY-MM-DD'))
 returning id into rid;
 update public.rooms set status = 'Reserved' where id = p_room_id;
 invoice := 'INV-'||extract(year from now())::text||'-'||upper(substr(replace(gen_random_uuid()::text,'-',''),1,10));
 insert into public.billings ("invoiceNumber","reservationId","roomCharges",subtotal,"taxAmount","serviceCharge",
   "grandTotal","balanceAmount",status,"createdAt")
 values (invoice,rid,total,total,round(total*0.12,2),round(total*0.10,2),
   round(total*1.22,2),round(total*1.22,2),'Unpaid',to_char(now() at time zone 'UTC','YYYY-MM-DD'))
 returning id into bid;
 insert into public.billing_items ("billingId",description,quantity,"unitPrice",amount)
 values(bid, 'Room Charge (Room '||r.number||' - '||p_nights||' Night/s)',p_nights,r."ratePerNight",total);
 return rid;
end $$;
revoke all on function public.create_hotel_reservation(bigint,bigint,text,text,integer,integer,integer,text) from public, anon;
grant execute on function public.create_hotel_reservation(bigint,bigint,text,text,integer,integer,integer,text) to authenticated;

create index if not exists reservations_room_status_idx on public.reservations ("roomId",status);
create index if not exists reservations_created_idx on public.reservations ("createdAt");
create index if not exists payments_paid_idx on public.payments ("paidAt");

